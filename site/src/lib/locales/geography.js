/**
 * Matches a query needle across all 4 localized variations of city, prefecture, and region.
 * Enables zero-friction cross-lingual venue and show discovery in SearchBox (ADR-0108).
 */
export function matchGeography(needle, city = "", prefecture = "", region = "") {
  if (!needle) return false;
  const n = needle.toLowerCase();
  const cZh = geoZhTw.cities[city] || city;
  const cJa = geoJa.cities[city] || "";
  const cEn = geoEn.cities[city] || "";
  const cKo = geoKo.cities[city] || "";

  const pZh = geoZhTw.prefectures[prefecture] || prefecture;
  const pJa = geoJa.prefectures[prefecture] || "";
  const pEn = geoEn.prefectures[prefecture] || "";
  const pKo = geoKo.prefectures[prefecture] || "";

  return (
    cZh.toLowerCase().includes(n) ||
    cJa.toLowerCase().includes(n) ||
    cEn.toLowerCase().includes(n) ||
    cKo.toLowerCase().includes(n) ||
    pZh.toLowerCase().includes(n) ||
    pJa.toLowerCase().includes(n) ||
    pEn.toLowerCase().includes(n) ||
    pKo.toLowerCase().includes(n) ||
    region.toLowerCase().includes(n)
  );
}
